truncate public.logs, public.dokumen, public.usulan;

alter table public.usulan drop column if exists tahap_saat_ini;
alter table public.usulan add column if not exists sop_kode text not null default 'otk';
alter table public.usulan add column if not exists langkah_saat_ini integer not null default 1;
alter table public.usulan add column if not exists prioritas text;

create table if not exists public.catatan_progres (
  id bigint generated by default as identity primary key,
  usulan_kode text not null references public.usulan (kode),
  tanggal date not null,
  progres text not null,
  tindak_lanjut text not null default '',
  oleh_siapa text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists catatan_progres_usulan_kode_idx on public.catatan_progres (usulan_kode);

alter table public.catatan_progres enable row level security;

drop policy if exists "open select" on public.catatan_progres;
drop policy if exists "open insert" on public.catatan_progres;
drop policy if exists "open update" on public.catatan_progres;
create policy "open select" on public.catatan_progres for select to anon, authenticated using (true);
create policy "open insert" on public.catatan_progres for insert to anon, authenticated with check (true);
create policy "open update" on public.catatan_progres for update to anon, authenticated using (true) with check (true);

-- Kolom audit sunting keterangan log (dari fitur sunting Lini Masa) dan
-- publikasi Realtime, untuk database lama yang belum memilikinya.
alter table public.logs add column if not exists keterangan_edited_at date;
alter table public.logs add column if not exists keterangan_edited_by text;

do $$
declare t text;
begin
  foreach t in array array['usulan', 'dokumen', 'logs', 'catatan_progres'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;
